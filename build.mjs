import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const root=new URL('./',import.meta.url);
const sources=await Promise.all(['data.js','config.js','asset-sizes.js','app.js'].map(file=>readFile(new URL(file,root),'utf8')));
const code=sources.map(s=>s.replace(/^import .*;\n/gm,'').replace(/^export /gm,'')).join('\n');
await writeFile(new URL('app.bundle.js',root),'/* Generated by build.mjs. Edit app.js, data.js, config.js. */\n(()=>{\n'+code+'\n})();\n');
console.log('Готово: app.bundle.js');
